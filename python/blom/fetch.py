import argparse
import gzip
import json
import sys
import urllib.request
import zlib
from collections import Counter
from collections.abc import Iterable, Iterator, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from types import TracebackType
from typing import IO, Self

import pyarrow.parquet as pq

SEPARATOR = "<|endoftext|>"
SPECIAL_TOKENS = ("<|endoftext|>", "<|im_start|>", "<|im_end|>")
CODEPARROT_URL = (
    "https://huggingface.co/datasets/codeparrot/codeparrot-clean/resolve/main/"
    "file-{index:012d}.json.gz"
)
CODEPARROT_FILES = 54
FINEWEB_URL = (
    "https://huggingface.co/datasets/HuggingFaceTB/smollm-corpus/resolve/main/"
    "fineweb-edu-dedup/train-{index:05d}-of-00234.parquet"
)
FINEWEB_FILES = 234
PERMISSIVE = frozenset(
    {"mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "isc", "unlicense", "cc0-1.0"}
)
CODE_VALID_MODULUS = 100
TEXT_VALID_MODULUS = 200
CHUNK = 1 << 20
BATCH_ROWS = 1024
TIMEOUT_SECONDS = 60


class FetchError(ValueError):
    pass


@dataclass(frozen=True)
class CodeRule:
    licenses: frozenset[str] = PERMISSIVE
    min_chars: int = 200
    max_chars: int = 100_000
    max_line: int = 400
    min_alpha: float = 0.25


@dataclass(frozen=True)
class TextRule:
    min_chars: int = 200
    max_chars: int = 100_000


@dataclass
class Stats:
    kept: Counter[str] = field(default_factory=Counter)
    rejected: Counter[str] = field(default_factory=Counter)
    chars: Counter[str] = field(default_factory=Counter)


def is_valid_key(key: str, modulus: int) -> bool:
    return zlib.crc32(key.encode("utf-8")) % modulus == 0


def is_valid_repo(repo: str) -> bool:
    return is_valid_key(repo, CODE_VALID_MODULUS)


def normalise(content: str) -> str:
    return content.replace("\r\n", "\n").replace("\r", "\n").rstrip() + "\n"


def clean_code(record: dict[str, object], rule: CodeRule) -> tuple[str | None, str]:
    content = record.get("content")
    license_name = record.get("license")
    alpha = record.get("alpha_frac")
    generated = record.get("autogenerated")
    if (
        not isinstance(content, str)
        or not isinstance(license_name, str)
        or isinstance(alpha, bool)
        or not isinstance(alpha, int | float)
    ):
        return None, "malformed"
    if license_name not in rule.licenses:
        return None, "license"
    if generated is True:
        return None, "autogenerated"
    if alpha < rule.min_alpha:
        return None, "alpha"
    text = normalise(content)
    if len(text) < rule.min_chars:
        return None, "short"
    if len(text) > rule.max_chars:
        return None, "long"
    if any(len(line) > rule.max_line for line in text.split("\n")):
        return None, "wide_line"
    if any(token in text for token in SPECIAL_TOKENS):
        return None, "special_token"
    try:
        text.encode("utf-8")
    except UnicodeEncodeError:
        return None, "unencodable"
    return text, "kept"


def clean_text(content: object, rule: TextRule) -> tuple[str | None, str]:
    if not isinstance(content, str):
        return None, "malformed"
    text = normalise(content)
    if len(text) < rule.min_chars:
        return None, "short"
    if len(text) > rule.max_chars:
        return None, "long"
    if any(token in text for token in SPECIAL_TOKENS):
        return None, "special_token"
    try:
        text.encode("utf-8")
    except UnicodeEncodeError:
        return None, "unencodable"
    return text, "kept"


def iter_records(path: Path) -> Iterator[dict[str, object]]:
    with gzip.open(path, "rt", encoding="utf-8") as handle:
        for number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError as error:
                raise FetchError(f"{path} line {number}: {error}") from error
            if not isinstance(record, dict):
                raise FetchError(f"{path} line {number}: not a JSON object")
            yield record


def iter_parquet(path: Path) -> Iterator[tuple[object, object]]:
    parquet = pq.ParquetFile(path)
    for batch in parquet.iter_batches(batch_size=BATCH_ROWS, columns=["text", "id"]):
        texts = batch.column("text").to_pylist()
        keys = batch.column("id").to_pylist()
        yield from zip(texts, keys, strict=True)


class SplitWriter:
    def __init__(self, train_out: Path, valid_out: Path, modulus: int) -> None:
        self.train_out = train_out
        self.valid_out = valid_out
        self.modulus = modulus
        self.stats = Stats()
        self.train_part = train_out.with_name(train_out.name + ".part")
        self.valid_part = valid_out.with_name(valid_out.name + ".part")
        self.train: IO[str] | None = None
        self.valid: IO[str] | None = None

    def __enter__(self) -> Self:
        self.train_out.parent.mkdir(parents=True, exist_ok=True)
        self.valid_out.parent.mkdir(parents=True, exist_ok=True)
        self.train = self.train_part.open("w", encoding="utf-8", newline="\n")
        self.valid = self.valid_part.open("w", encoding="utf-8", newline="\n")
        return self

    def __exit__(
        self,
        kind: type[BaseException] | None,
        error: BaseException | None,
        trace: TracebackType | None,
    ) -> None:
        for handle in (self.train, self.valid):
            if handle is not None:
                handle.close()
        if kind is None:
            self.train_part.replace(self.train_out)
            self.valid_part.replace(self.valid_out)
        else:
            self.train_part.unlink(missing_ok=True)
            self.valid_part.unlink(missing_ok=True)

    def add(self, text: str, key: str) -> None:
        split = "valid" if is_valid_key(key, self.modulus) else "train"
        handle = self.valid if split == "valid" else self.train
        if handle is None:
            raise FetchError("writer is not open")
        handle.write(f"{text}{SEPARATOR}\n")
        self.stats.kept[split] += 1
        self.stats.chars[split] += len(text)


def convert_code(
    sources: Sequence[Path], train_out: Path, valid_out: Path, rule: CodeRule
) -> Stats:
    with SplitWriter(train_out, valid_out, CODE_VALID_MODULUS) as writer:
        for source in sources:
            for record in iter_records(source):
                repo = record.get("repo_name")
                text, reason = clean_code(record, rule)
                if text is None or not isinstance(repo, str):
                    writer.stats.rejected[reason if text is None else "malformed"] += 1
                    continue
                writer.add(text, repo)
    return writer.stats


def convert_text(
    sources: Sequence[Path], train_out: Path, valid_out: Path, rule: TextRule
) -> Stats:
    with SplitWriter(train_out, valid_out, TEXT_VALID_MODULUS) as writer:
        for source in sources:
            pairs: Iterable[tuple[object, object]] = iter_parquet(source)
            for content, key in pairs:
                text, reason = clean_text(content, rule)
                if text is None or not isinstance(key, str):
                    writer.stats.rejected[reason if text is None else "malformed"] += 1
                    continue
                writer.add(text, key)
    return writer.stats


def download(url: str, dest: Path) -> bool:
    if dest.exists() and dest.stat().st_size > 0:
        return False
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_name(dest.name + ".part")
    written = 0
    with urllib.request.urlopen(url, timeout=TIMEOUT_SECONDS) as response, part.open("wb") as out:
        expected = response.headers.get("Content-Length")
        while chunk := response.read(CHUNK):
            out.write(chunk)
            written += len(chunk)
    if expected is not None and written != int(expected):
        part.unlink()
        raise FetchError(f"{url}: got {written} bytes, expected {expected}")
    part.replace(dest)
    return True


def download_all(
    url_template: str, name: str, suffix: str, count: int, first: int, folder: Path
) -> list[Path]:
    paths: list[Path] = []
    for offset in range(count):
        dest = folder / f"{name}-{offset + 1:03d}{suffix}"
        fresh = download(url_template.format(index=first + offset), dest)
        print(f"{'downloaded' if fresh else 'have'} {dest.name}", flush=True)
        paths.append(dest)
    return paths


def check_count(files: int, limit: int) -> None:
    if not 1 <= files <= limit:
        raise FetchError(f"files must be between 1 and {limit}")


def fetch_codeparrot(files: int, download_dir: Path, out_dir: Path, rule: CodeRule) -> Stats:
    check_count(files, CODEPARROT_FILES)
    sources = download_all(CODEPARROT_URL, "codeparrot", ".json.gz", files, 1, download_dir)
    return convert_code(sources, out_dir / "code_train.txt", out_dir / "code_valid.txt", rule)


def fetch_fineweb(files: int, download_dir: Path, out_dir: Path, rule: TextRule) -> Stats:
    check_count(files, FINEWEB_FILES)
    sources = download_all(FINEWEB_URL, "fineweb", ".parquet", files, 0, download_dir)
    return convert_text(sources, out_dir / "text_train.txt", out_dir / "text_valid.txt", rule)


def report(stats: Stats) -> None:
    for split in ("train", "valid"):
        print(f"{split}: {stats.kept[split]} documents, {stats.chars[split]} characters")
    reasons = ", ".join(f"{k} {v}" for k, v in stats.rejected.most_common())
    print(f"rejected: {reasons or 'none'}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="blom.fetch", description="Fetch training text")
    commands = parser.add_subparsers(dest="command", required=True)
    for name, help_text, limit in (
        ("codeparrot", "Python code from codeparrot-clean", CODEPARROT_FILES),
        ("fineweb", "Educational web text from FineWeb-Edu", FINEWEB_FILES),
    ):
        sub = commands.add_parser(name, help=help_text)
        sub.add_argument("--files", type=int, required=True, help=f"How many of the {limit} files")
        sub.add_argument("--download-dir", type=Path, required=True)
        sub.add_argument("--out-dir", type=Path, required=True)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.command == "codeparrot":
            stats = fetch_codeparrot(args.files, args.download_dir, args.out_dir, CodeRule())
        else:
            stats = fetch_fineweb(args.files, args.download_dir, args.out_dir, TextRule())
    except (FetchError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    report(stats)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
